/**
 * HTTP API of the panel.
 *
 * Routes are registered on the Harness connection channel, so the shared web
 * handler authenticates the browser session before a handler runs; the panel
 * only ever talks to these endpoints. Route paths are exact (the channel does
 * not template path segments), so identifiers travel as query parameters.
 *
 * Route list:
 *   GET  /api/learnway/health
 *   GET  /api/learnway/lessons
 *   GET  /api/learnway/lesson?id=…
 *   POST /api/learnway/grade    {id, answers:[{index, choice}]}
 *   POST /api/learnway/delete   {id}
 *   POST /api/learnway/ping     {phase, moduleId, registrations}
 *   POST /api/learnway/export   {id, formats:['pptx','html','md']}
 *   GET  /api/learnway/export?id=…&file=deck.pptx
 *
 * @module host/api
 */

import { readFile } from 'node:fs/promises'
import { basename, join } from 'node:path'

/**
 * Exact route prefix registered on the Harness connection channel.
 * `dsh-client-connection` validates and dispatches exact Fetch routes by the
 * full request pathname under `/api/*`, so every route registers with this
 * prefix directly.
 */
export const API_PREFIX = '/api/learnway'

/** The only files the download route will serve, by exact name. */
const DOWNLOADABLE = {
  'deck.pptx': 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  'deck.html': 'text/html; charset=utf-8',
  'deck.md': 'text/markdown; charset=utf-8',
}

/** Lesson ids are generated by this plugin; anything else is not a path. */
const SAFE_ID = /^[A-Za-z0-9_-]{1,64}$/

/** Body ceiling: a lesson is text, so anything larger is a mistake. */
const MAX_BODY_BYTES = 4 * 1024 * 1024

/** JSON response helper. */
function json(body, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' },
  })
}

/** Failure shaped the same way everywhere. */
function failure(code, message, status = 400) {
  return json({ ok: false, error: { code, message } }, status)
}

/** Read a bounded JSON body. */
async function readJsonBody(request) {
  const declared = Number(request.headers.get('content-length') ?? 0)
  if (declared > MAX_BODY_BYTES) throw Object.assign(new Error('请求体超过 4MB'), { code: 'body-too-large' })
  const body = await request.text()
  if (body.length > MAX_BODY_BYTES) throw Object.assign(new Error('请求体超过 4MB'), { code: 'body-too-large' })
  if (body.trim().length === 0) return {}
  try {
    return JSON.parse(body)
  } catch {
    throw Object.assign(new Error('请求体不是合法 JSON'), { code: 'invalid-json' })
  }
}

/**
 * Build the route table.
 *
 * @param {ReturnType<import('./service.js').createLearnwayService>} service
 * @param {{log?: (message: string) => void}} [options]
 */
export function createApiRoutes(service, options = {}) {
  const log = options.log ?? (() => {})
  // Every failure becomes a JSON 500 with a reason instead of a bare 400.
  const safe = (handler) => async (request) => {
    try {
      return await handler(request)
    } catch (error) {
      log(`${request.method} ${new URL(request.url).pathname} failed: ${error?.stack ?? error}`)
      return failure(error?.code ?? 'internal-error', String(error?.message ?? error), 500)
    }
  }
  // GET routes declare a buffered body: the bridge builds a streaming Request
  // otherwise, and constructing a GET-with-body Request throws.
  const route = (path, methods, handler, requestBody = 'buffered') => ({
    // Exact path under `/api`: dsh-client-connection validates and matches the full pathname.
    path: `${API_PREFIX}${path}`,
    methods,
    requestBody,
    fetch: safe(handler),
  })

  return [
    route('/health', ['GET'], async () => json(await service.health())),

    route('/lessons', ['GET'], async () => json({ ok: true, lessons: await service.list() })),

    route('/ping', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      const entry = service.recordPing(body ?? {})
      return json({ ok: true, seen: entry.at })
    }),

    route('/lesson', ['GET'], async (request) => {
      const id = new URL(request.url).searchParams.get('id')
      if (!id) return failure('missing-id', '需要 id 参数', 400)
      const record = await service.get(id)
      if (!record) return failure('not-found', '没有该课时', 404)
      return json({ ok: true, ...record })
    }),

    route('/grade', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      const mode = body.mode === 'drill' ? 'drill' : 'full'
      const result = await service.grade(body.id, body.answers, { mode })
      if (!result) return failure('not-found', '没有该课时', 404)
      return json({ ok: true, ...result })
    }),

    route('/progress', ['GET'], async (request) => {
      const id = new URL(request.url).searchParams.get('id')
      if (!id) return failure('missing-id', '需要 id 参数', 400)
      const result = await service.getProgress(id)
      if (!result) return failure('not-found', '没有该课时', 404)
      return json({ ok: true, ...result })
    }),

    route('/review-queue', ['GET'], async (request) => {
      const limitParam = new URL(request.url).searchParams.get('limit')
      const limit = limitParam ? Number(limitParam) : undefined
      return json({ ok: true, ...(await service.reviewQueue({ limit })) })
    }),

    route('/reflect', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      if (body.index === undefined || body.index === null) return failure('missing-index', '需要 index 字段', 400)
      const result = await service.saveReflection(body.id, body.index, body.text ?? '')
      if (!result) return failure('not-found', '没有该课时', 404)
      return json({ ok: true, ...result })
    }),

    route('/audio-reply', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      const result = await service.evaluateAudioReply(body.id, {
        turnIndex: body.turnIndex,
        answer: body.answer,
        choiceIndex: typeof body.choiceIndex === 'number' ? body.choiceIndex : undefined,
        history: Array.isArray(body.history) ? body.history : undefined,
      })
      if (!result) return failure('not-found', '没有该课时', 404)
      return json(result)
    }),

    route('/profile', ['GET', 'POST'], async (request) => {
      if (request.method === 'GET') {
        return json({ ok: true, profile: await service.getProfile() })
      }
      const body = await readJsonBody(request)
      const updated = await service.updateProfile(body ?? {})
      return json({ ok: true, profile: updated })
    }),

    route('/reflect-grade', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      if (body.index === undefined || body.index === null) return failure('missing-index', '需要 index 字段', 400)
      const result = await service.evaluateReflection(body.id, body.index, body.text ?? '')
      if (!result) return failure('not-found', '没有该课时', 404)
      return json({ ok: true, ...result })
    }),

    route('/variant', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      if (body.index === undefined || body.index === null) return failure('missing-index', '需要 index 字段', 400)
      const result = await service.generateVariantQuestion(body.id, body.index)
      if (!result) return failure('not-found', '没有该课时', 404)
      return json(result)
    }),

    route('/reexplain', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      const result = await service.reexplainBlock(body.id, { text: body.text, mode: body.mode })
      if (!result) return failure('not-found', '没有该课时', 404)
      return json(result)
    }),

    // One path, both methods: a registry keyed by path must never see two
    // registrations for `/export`.
    route('/export', ['GET', 'POST'], async (request) => {
      if (request.method === 'GET') {
        const url = new URL(request.url)
        const id = url.searchParams.get('id') ?? ''
        const name = url.searchParams.get('file') ?? ''
        if (!SAFE_ID.test(id)) return failure('invalid-id', 'id 不合法', 400)
        // The name is a key in a fixed table, never a caller-supplied path.
        const type = DOWNLOADABLE[name]
        if (!type) return failure('invalid-file', `file 只能是 ${Object.keys(DOWNLOADABLE).join(' / ')}`, 400)
        const file = join(service.exportDir(id), basename(name))
        let bytes
        try {
          bytes = await readFile(file)
        } catch {
          return failure('not-exported', '还没有导出该文件，先在面板或工具里导出一次', 404)
        }
        return new Response(bytes, {
          status: 200,
          headers: {
            'content-type': type,
            'content-length': String(bytes.byteLength),
            'cache-control': 'no-store',
            'content-disposition': `attachment; filename="learnway-${id}-${name}"`,
          },
        })
      }
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      const formats = Array.isArray(body.formats) ? body.formats.map(String) : undefined
      const theme = typeof body.theme === 'string' ? body.theme : undefined
      const result = await service.exportDeck(String(body.id), formats, { theme })
      if (!result) return failure('not-found', '没有该课时', 404)
      return json({ ok: true, ...result })
    }),

    route('/delete', ['POST'], async (request) => {
      const body = await readJsonBody(request)
      if (!body.id) return failure('missing-id', '需要 id 字段', 400)
      const removed = await service.remove(body.id)
      return removed ? json({ ok: true, id: body.id }) : failure('not-found', '没有该课时', 404)
    }),
  ]
}
